#!/usr/bin/env node
// Generates the QA-only SQL for the families whose definitions exist only in production (ZURIEL 26.11.2026): tables, constraints, indexes,
// row level security, policies, functions, triggers and grants, exactly as read from production, with no row. It copies definitions, it does
// not write or rewrite any business logic. A trigger whose function is outside the extracted scope is left out and listed in the output header.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadDefinitions, KIND_ORDER } from './qa-prod-definitions-lib.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const objects = loadDefinitions(root);
const fnNames = new Set(objects.filter((o) => o.kind === 'function').map((o) => /^public\.(\w+)\(/.exec(o.name)[1]));
const excluded = [], body = [];
for (const kind of KIND_ORDER) for (const o of objects.filter((x) => x.kind === kind)) {
  if (kind === 'trigger') { const fn = /EXECUTE FUNCTION (\w+)\(/.exec(o.ddl)?.[1]; if (!fnNames.has(fn)) { excluded.push(`${o.name} (function ${fn} is outside the extracted scope)`); continue; } }
  body.push(`-- ${kind} ${o.name}\n${o.ddl}`);
}
const sql = ['-- QA-ONLY schema generated by scripts/build-qa-prod-definitions.mjs from qa/extract/prod-definitions.sql. Never applied to production.',
  ...excluded.map((line) => `-- excluded: ${line}`), ...body, 'grant all on all tables in schema public to service_role;', "notify pgrst, 'reload schema';"].join('\n\n');
writeFileSync(root + 'qa/supabase/migrations/20260101000050_qa_prod_defs.sql', sql);
console.log(`qa prod definitions written: ${objects.length} objects, ${excluded.length} trigger(s) excluded`);
