import {readdirSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {generatedMigration as combinedMigration} from './generate-follow-category-series-alignment.mjs';

// Reuse the SAME descriptors, producer and guarded live preimages. The root
// category rename is a separate release; pinned Legacy does not understand it.
const paths=readdirSync(new URL('../supabase/migrations/',import.meta.url)).filter(name=>/^\d{14}_follow_content_series_only_v1\.sql$/.test(name));
if(paths.length!==1)throw Error('Expected one CLI-created series-only migration');
export const migrationPath='supabase/migrations/'+paths[0];
export function generatedMigration(){
  const full=combinedMigration();
  const guard=full.match(/do \$guard\$[\s\S]*?\$guard\$;/)?.[0];
  const subject=full.match(/CREATE OR REPLACE FUNCTION public\.canonical_follow_subject[\s\S]*?\$function\$\s*;/)?.[0];
  const matcher=full.match(/-- Internal pure compatibility matcher[\s\S]*?revoke all on function public\.post_content_series_keys_v1\(text\[\],text\[\],text\) from public, anon, authenticated;/)?.[0];
  const producer=full.match(/create or replace function public\.notify_on_post_publish\(\)[\s\S]*?\$function\$;/)?.[0];
  const tail=full.slice(full.indexOf('-- Reuse the single trigger/dispatcher'));
  if(!guard||!subject||!matcher||!producer||!tail.endsWith('commit;\n'))throw Error('Existing Follow build artifact changed; review extractor');
  const helperGuard=`  if to_regprocedure('public.post_content_series_keys_v1(text[],text[],text)') is not null then
    raise exception 'Follow alignment base changed: series helper already exists; re-review';
  end if;
`;
  return `-- GENERATED by scripts/generate-follow-content-series-only.mjs; do not hand-edit.
-- BRANCH-ONLY SERIES CANDIDATE, NOT APPLIED. Owner: subscription_funnel_law v21.
-- Preserves Legacy canonical_follow_topic/follow_topic_aliases byte-for-byte.
-- No category rename, preference rewrite, history backfill, ACL expansion or external delivery.
begin;
${guard.replace('end\n$guard$;',helperGuard+'end\n$guard$;')}

${subject}

${matcher}

${producer}

${tail}`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  const file=new URL('../'+migrationPath,import.meta.url),sql=generatedMigration();
  if(process.argv.includes('--check')){
    if(readFileSync(file,'utf8')!==sql)throw Error('Series-only migration is stale');
    console.log('Series-only migration matches shared descriptors; Legacy category functions untouched');
  }else{writeFileSync(file,sql);console.log(migrationPath);}
}
