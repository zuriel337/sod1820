// One owner for "which vercel.json sources must Edge route legitimacy know?". route-legitimacy.js keeps its hand-written
// list of App routes; everything that vercel.json already declares (single-segment redirect and 2029 rewrite sources)
// is DERIVED here into a marked block, so adding a redirect can never again require remembering a second list. The exact
// single-segment App routes are derived the same way, from the router itself (src/App2029.jsx, production scope projection).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { productionApp2029Source } from "./public-preview-route-scope.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const read = p => readFileSync(root + p, "utf8");
export const START = "  // <derived:vercel-single-segment-sources> generated by scripts/sync-route-legitimacy.mjs; do not edit by hand";
export const END = "  // </derived:vercel-single-segment-sources>";
const CONFIGS = ["vercel.json", "public-reading-deploy/vercel.json"];

// The Edge middleware only runs on paths its exported matcher matches. Paths with a dot (files such as /tzofen.html,
// /sitemap.xml), /api/ and /assets/ never reach it, so they never need legitimacy registration.
export function middlewareMatcher() {
  const literal = read("middleware.js").match(/matcher:\s*\[\s*'([^']+)'\s*\]/);
  if (!literal) throw new Error("middleware.js matcher literal not found");
  return new RegExp("^" + literal[1].replace(/\\\\/g, "\\") + "$");
}
export const middlewareSees = (matcher, path) => matcher.test(path);

const isSingleSegment = p => {
  if (!p.startsWith("/")) return false;
  const rest = p.slice(1);
  return Boolean(rest) && !rest.includes("/") && !rest.includes("(") && !rest.includes(":") && !rest.includes("*");
};
const decode = p => { try { return decodeURIComponent(p); } catch { return p; } };

// Exact single-segment routes of the 2029 router as it ships in production (no params, no wildcards).
export function appRoutes() {
  const source = productionApp2029Source(read("src/App2029.jsx"));
  return [...source.matchAll(/<Route\s+path="([^"]+)"/g)].map(m => m[1]).filter(isSingleSegment);
}

export function derivedSources() {
  const matcher = middlewareMatcher();
  const out = new Set(appRoutes().map(decode));
  for (const file of CONFIGS) {
    const config = JSON.parse(read(file));
    const sources = [
      ...(config.redirects || []).map(r => r.source),
      ...(config.rewrites || []).filter(r => r.destination === "/2029.html").map(r => r.source),
    ];
    for (const source of sources) if (isSingleSegment(source) && middlewareSees(matcher, source)) out.add(decode(source));
  }
  return [...out].sort();
}

export function syncRouteLegitimacy({ write = false } = {}) {
  const file = "route-legitimacy.js";
  const text = read(file);
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error("route-legitimacy.js has no derived block markers");
  const manual = text.slice(0, a) + text.slice(b + END.length);
  const manualHas = new Set([...manual.matchAll(/^ {2}"(\/[^"]+)",$/gm)].map(m => m[1]));
  const lines = derivedSources().filter(route => !manualHas.has(route)).map(route => `  "${route}",`);
  const next = text.slice(0, a) + START + "\n" + lines.join("\n") + (lines.length ? "\n" : "") + text.slice(b);
  if (write && next !== text) writeFileSync(root + file, next);
  return { upToDate: next === text, next, routes: lines.length };
}
