#!/usr/bin/env node
// Builds the QA-only ELS schema for the throwaway local Supabase (ZURIEL 26.11.2026) from definitions the repository already owns, so the QA
// stack cannot drift from them: the isolated ELS fixture (tables, policies, corpus helpers), the stubs of the tiers tests, and the proposed
// SQL (apply.sql, harden-grants.sql) that production runs. Output is generated at job time and never applied to production.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFileSync(root + path, 'utf8');
const stripGuard = sql => sql.replace(/^do \$guard\$[\s\S]*?^\$guard\$;\s*$/m, '').replace(/^\s*(begin|commit);\s*$/gm, '')
  // production already ran apply.sql: its constraint is part of the real table definition read from production, so it is not added a second time
  .replace(/^alter table public\.els_records add constraint els_records_private_not_self_published_chk[^\n]*$/m, '');

const fixture = read('test/els-native-save-fixture.sql');
// The fixture's els_records, its row level security, its policies and its grants are replaced by the real definition read from production: start after them.
const from = fixture.indexOf('create function fn_els_term_norm');
const to = fixture.indexOf('grant select on research_contributions,test_publish_gate_calls to authenticated;');
if (from < 0 || to < 0) throw new Error('fixture_markers_missing');
// The fixture's stand-ins for functions that production owns (corpus id, term normalisation, slug, publish truth gate) are replaced by the real definitions read from production.
const REAL = ['fn_els_term_norm', 'fn_els_corpus_id', 'els_slugify', 'els_publish_truth_gate_v1'];
const stripReal = text => REAL.reduce((out, name) => out.replace(new RegExp(`^create function ${name}\\([\\s\\S]*?(?:\\$\\$;|\\$\\$)\\s*;?\\s*$`, 'm'), ''), text);
const tables = stripReal(fixture.slice(from, to)).split('\n').filter(line => !/^grant select on els_records,users/.test(line))
  // research_contributions is the real definition read from production (comments family), not the fixture's reduced stand-in
  .filter(line => !/^create table research_contributions\(/.test(line)).join('\n');

const pre = read('test/els-publication-tiers-pre.sql').split('\n');
const stubsEnd = pre.findIndex(line => line.startsWith('create function public.self_publish_matrix'));
// users and user_notifications are the real definitions read from production (qa/extract/prod-definitions.sql, applied first), not stubs.
const stubs = pre.slice(0, stubsEnd).filter(line => !/^--/.test(line) && !/^update users set email/.test(line) && !/^create table user_notifications\(/.test(line)).join('\n');

const sql = [
  '-- QA-ONLY ELS schema, generated by scripts/build-qa-schema.mjs. Never applied to production.',
  tables,
  stubs.replace(/^alter table users add column email text;\s*$/m, ''),
  'grant select on public.user_notifications, public.system_suggestions to service_role;',
  stripGuard(read('supabase/proposed/els-publication-tiers-20261126/apply.sql')),
  stripGuard(read('supabase/proposed/els-publication-tiers-20261126/harden-grants.sql')),
  'grant all on all tables in schema public to service_role;',
  "notify pgrst, 'reload schema';",
].join('\n\n');
mkdirSync(root + 'qa/supabase/migrations', { recursive: true });
writeFileSync(root + 'qa/supabase/migrations/20260101000100_qa_els.sql', sql);
console.log(`qa schema written (${sql.length} characters)`);
