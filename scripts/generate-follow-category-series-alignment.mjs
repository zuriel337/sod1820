import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { CONTENT_SERIES_2029 } from "../src/lib/research/contentSeries2029Identity.js";

// A reproducible SQL build artifact of the same exact compatibility descriptors.
// Never connects to a database. Applying the migration is a separate release gate.
export const migrationPath = "supabase/migrations/20261026012207_follow_category_series_alignment_v1.sql";
const snapshot = readFileSync(new URL("../tests/fixtures/follow-engine-live-20261026.sql", import.meta.url), "utf8");
const definitions = [...snapshot.matchAll(/(CREATE OR REPLACE FUNCTION public\.(\w+)[\s\S]*?\$function\$);/g)];
const preimages = Object.fromEntries(definitions.map(([, source, name]) => [name, source + "\n"]));
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const md5 = source => createHash("md5").update(source).digest("hex");

export function generatedMigration() {
  const topic = preimages.canonical_follow_topic.replace("return 'cat:' || v_label;",
    "return 'cat:' || case when v_label = 'רמזי הגאולה' then 'רמזים חזקים' else v_label end;");
  const aliases = preimages.follow_topic_aliases.replace("'category:' || v_straight\n", "'category:' || v_straight,\n        case when v_label = 'רמזים חזקים' then 'cat:רמזי הגאולה' end,\n        case when v_label = 'רמזים חזקים' then 'category:רמזי הגאולה' end\n");
  const keys = CONTENT_SERIES_2029.map(spec => quote(spec.key)).join(", ");
  const subject = preimages.canonical_follow_subject.replace("    when 'cipher_feed'", `    when 'series'         then case when v_id in (${keys}) then 'series:' || v_id else '' end\n    when 'cipher_feed'`);
  const matches = CONTENT_SERIES_2029.map(spec => {
    const membership = spec.membership.map(({ field, value }) => `${quote(value)} = any(coalesce(p_${field}, '{}'::text[]))`).join(" or ");
    const author = spec.exactAuthor ? ` and coalesce(p_author, '') = ${quote(spec.exactAuthor)}` : "";
    return `    (${quote(spec.key)}, (${membership})${author})`;
  }).join(",\n");
  const argsByName = { canonical_follow_topic: "text", follow_topic_aliases: "text", canonical_follow_subject: "text,text", notify_on_post_publish: "", resolve_topics: "text,text", dispatch: "text,text,text,text,text,text,text,uuid", watch_toggle: "text,text,boolean,text" };
  const guard = Object.keys(argsByName).map(name => {
    const args = argsByName[name];
    return `  if md5(pg_get_functiondef('public.${name}(${args})'::regprocedure)) <> '${md5(preimages[name])}' then\n    raise exception 'Follow alignment base changed: ${name}; re-review instead of overwriting';\n  end if;`;
  }).join("\n");
  const sql = `-- GENERATED by scripts/generate-follow-category-series-alignment.mjs; do not hand-edit.
-- BRANCH-ONLY CANDIDATE, NOT APPLIED. Owner: subscription_funnel_law v19.
-- Shared descriptors originate at 780db978, PLAN37 DEC-SERIES-003/004/005/006.
-- No preference rewrite, history backfill, RLS/grant expansion, or external delivery.
begin;

do $guard$
begin
${guard}
  if not exists (select 1 from pg_trigger where tgrelid = 'public.posts'::regclass and tgname = 'trg_posts_notify' and pg_get_triggerdef(oid) = 'CREATE TRIGGER trg_posts_notify AFTER INSERT ON public.posts FOR EACH ROW EXECUTE FUNCTION notify_on_post_publish()') then
    raise exception 'Follow alignment base changed: post trigger; re-review instead of overwriting';
  end if;
end
$guard$;

${topic};
${aliases};
${subject};

-- Internal pure compatibility matcher; not an exposed entity registry or RPC.
create function public.post_content_series_keys_v1(p_categories text[], p_tags text[], p_author text)
returns text[] language sql immutable set search_path = ''
as $series$
  select coalesce(array_agg(series_key order by series_key) filter(where matches), '{}'::text[])
  from (values
${matches}
  ) as approved(series_key, matches);
$series$;
revoke all on function public.post_content_series_keys_v1(text[],text[],text) from public, anon, authenticated;

create or replace function public.notify_on_post_publish()
returns trigger language plpgsql security definer set search_path = public
as $function$
declare c text; s text;
begin
  -- Taxonomy/author/title edits never become new publication events. Only an
  -- explicit transition out of draft/forum can publish an existing recent row.
  if TG_OP = 'UPDATE' and not (coalesce(OLD.tags, '{}'::text[]) && array['טיוטה','פורום']) then return NEW; end if;
  if coalesce(NEW.tags, '{}'::text[]) && array['טיוטה','פורום'] then return NEW; end if;
  if nullif(btrim(NEW.slug), '') is null then return NEW; end if;
  if coalesce(NEW.date, now()) < now() - interval '2 hours' then return NEW; end if;
  if NEW.categories is not null then
    foreach c in array NEW.categories loop
      if c is not null and btrim(c) <> '' then
        perform public.dispatch('category', c, 'post_new', NEW.id::text,
          'פוסט חדש ב' || c, NEW.title, '/' || NEW.slug);
      end if;
    end loop;
  end if;
  if NEW.author is not null and btrim(NEW.author) <> '' and NEW.author <> 'המערכת' then
    perform public.dispatch('author', NEW.author, 'post_new', NEW.id::text,
      'פוסט חדש מאת ' || NEW.author, NEW.title, '/' || NEW.slug);
  end if;
  foreach s in array public.post_content_series_keys_v1(NEW.categories, NEW.tags, NEW.author) loop
    perform public.dispatch('series', s, 'post_new', NEW.id::text,
      'פרסום חדש בסדרה', NEW.title, '/' || NEW.slug);
  end loop;
  return NEW;
end
$function$;

-- Reuse the single trigger/dispatcher and its existing recipient+event dedupe.
drop trigger if exists trg_posts_notify on public.posts;
create trigger trg_posts_notify after insert or update of tags on public.posts
for each row execute function public.notify_on_post_publish();
commit;
`;
  return sql;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = generatedMigration();
  const path = new URL("../" + migrationPath, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== generated) throw new Error("Generated Follow migration is stale");
    console.log("Follow migration matches shared series descriptors");
  } else {
    writeFileSync(path, generated);
    console.log(migrationPath);
  }
}
