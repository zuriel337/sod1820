-- CardCom admin-only recurring membership pilot.
-- Fixed pilot economics: ILS 2 charged immediately, then monthly until cancelled.
-- No card number or CVV is stored. The CardCom token is encrypted by the server
-- before it reaches Postgres and is kept in the non-exposed private schema.

begin;

-- The canonical private schema already exists. Do not alter its shared ACLs.
do $$
begin
  if to_regnamespace('private') is null then raise exception 'private_schema_required'; end if;
  if has_schema_privilege('anon','private','usage')
     or has_schema_privilege('authenticated','private','usage') then
    raise exception 'private_schema_must_already_be_restricted';
  end if;
end $$;

create table public.membership_subscription_pilots (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider_ref text not null unique,
  cardcom_low_profile_id text not null unique,
  amount_ils numeric(10,2) not null default 2.00 check (amount_ils = 2.00),
  interval_months integer not null default 1 check (interval_months = 1),
  status text not null default 'pending'
    check (status in ('pending','active','renewing','past_due','cancelled')),
  initial_transaction_id text unique,
  initial_document_url text,
  current_period_start timestamptz,
  current_period_end timestamptz,
  next_charge_at timestamptz,
  cancel_at_period_end boolean not null default false,
  last_response_code integer,
  failure_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.membership_subscription_pilots is
  'Admin-only ILS 2 CardCom token billing pilot. Not a public membership product.';

create table private.cardcom_subscription_credentials (
  subscription_id uuid primary key references public.membership_subscription_pilots(id) on delete cascade,
  billing_name text not null,
  billing_email text,
  token_ciphertext text,
  token_iv text,
  token_tag text,
  expiration_mmyy text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (expiration_mmyy is null or expiration_mmyy ~ '^[0-9]{4}$')
);

create table public.membership_subscription_pilot_charges (
  id bigint generated by default as identity primary key,
  subscription_id uuid not null references public.membership_subscription_pilots(id) on delete cascade,
  external_uniq_tran_id text not null unique,
  kind text not null check (kind in ('initial','renewal')),
  amount_ils numeric(10,2) not null check (amount_ils = 2.00),
  status text not null check (status in ('pending','approved','failed')),
  cardcom_transaction_id text unique,
  response_code integer,
  document_url text,
  attempted_at timestamptz not null default now(),
  settled_at timestamptz
);

create index membership_subscription_pilots_user_created_idx
  on public.membership_subscription_pilots (user_id, created_at desc);

-- Concurrent checkout attempts must not create two payable subscriptions.
create unique index membership_subscription_pilots_one_open_per_user_idx
  on public.membership_subscription_pilots (user_id)
  where status in ('pending','active','renewing','past_due');

create index membership_subscription_pilots_due_idx
  on public.membership_subscription_pilots (next_charge_at, created_at)
  where status in ('active','renewing');

create index membership_subscription_pilot_charges_subscription_idx
  on public.membership_subscription_pilot_charges (subscription_id, attempted_at desc);

alter table public.membership_subscription_pilots enable row level security;
alter table public.membership_subscription_pilot_charges enable row level security;
alter table private.cardcom_subscription_credentials enable row level security;
revoke all on private.cardcom_subscription_credentials from public, anon, authenticated;

create policy membership_subscription_pilots_select_own
on public.membership_subscription_pilots for select
to authenticated
using (
  (select auth.uid()) = user_id
  or exists (
    select 1 from public.users u
    where u.id = (select auth.uid()) and u.role = 'admin'
  )
);

create policy membership_subscription_pilot_charges_select_own
on public.membership_subscription_pilot_charges for select
to authenticated
using (
  exists (
    select 1
    from public.membership_subscription_pilots s
    where s.id = subscription_id
      and (
        s.user_id = (select auth.uid())
        or exists (
          select 1 from public.users u
          where u.id = (select auth.uid()) and u.role = 'admin'
        )
      )
  )
);

revoke all on public.membership_subscription_pilots from public, anon, authenticated;
revoke all on public.membership_subscription_pilot_charges from public, anon, authenticated;
grant select on public.membership_subscription_pilots to authenticated;
grant select on public.membership_subscription_pilot_charges to authenticated;

create or replace function public.membership_pilot_start_guard(
  p_bridge_secret text,
  p_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_existing public.membership_subscription_pilots%rowtype;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;
  if not exists (select 1 from public.users where id = p_user_id and role = 'admin') then
    raise exception 'admin_only';
  end if;

  select * into v_existing
  from public.membership_subscription_pilots
  where user_id = p_user_id
    and status in ('pending','active','renewing','past_due')
  order by created_at desc
  limit 1;

  if found then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'existing_subscription',
      'provider_ref', v_existing.provider_ref,
      'status', v_existing.status
    );
  end if;
  return jsonb_build_object('allowed', true);
end
$$;

create or replace function public.membership_pilot_register(
  p_bridge_secret text,
  p_user_id uuid,
  p_provider_ref text,
  p_low_profile_id text,
  p_billing_name text,
  p_billing_email text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','private','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_id uuid;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;
  if not exists (select 1 from public.users where id = p_user_id and role = 'admin') then
    raise exception 'admin_only';
  end if;
  if p_provider_ref !~ '^SODM-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    raise exception 'bad_provider_ref';
  end if;
  if p_low_profile_id is null or btrim(p_low_profile_id) = '' or length(p_low_profile_id) > 120 then
    raise exception 'bad_low_profile_id';
  end if;

  insert into public.membership_subscription_pilots(
    user_id, provider_ref, cardcom_low_profile_id
  ) values (
    p_user_id, p_provider_ref, btrim(p_low_profile_id)
  ) returning id into v_id;

  insert into private.cardcom_subscription_credentials(
    subscription_id, billing_name, billing_email
  ) values (
    v_id,
    left(coalesce(nullif(btrim(p_billing_name),''), 'SOD1820 member'), 120),
    nullif(left(btrim(coalesce(p_billing_email,'')), 254), '')
  );

  insert into public.membership_subscription_pilot_charges(
    subscription_id, external_uniq_tran_id, kind, amount_ils, status
  ) values (v_id, p_provider_ref, 'initial', 2.00, 'pending');

  return jsonb_build_object('subscription_id', v_id, 'provider_ref', p_provider_ref, 'status', 'pending');
end
$$;

create or replace function public.membership_pilot_webhook_lookup(
  p_bridge_secret text,
  p_low_profile_id text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_row public.membership_subscription_pilots%rowtype;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;
  select * into v_row from public.membership_subscription_pilots
  where cardcom_low_profile_id = btrim(coalesce(p_low_profile_id,''));
  if not found then return jsonb_build_object('known', false); end if;
  return jsonb_build_object(
    'known', true,
    'subscription_id', v_row.id,
    'provider_ref', v_row.provider_ref,
    'status', v_row.status,
    'amount_ils', v_row.amount_ils
  );
end
$$;

create or replace function public.membership_pilot_activate(
  p_bridge_secret text,
  p_subscription_id uuid,
  p_provider_ref text,
  p_transaction_id text,
  p_document_url text,
  p_token_ciphertext text,
  p_token_iv text,
  p_token_tag text,
  p_expiration_mmyy text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','private','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_row public.membership_subscription_pilots%rowtype;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;
  if p_expiration_mmyy !~ '^[0-9]{4}$' then raise exception 'bad_expiration'; end if;
  if nullif(btrim(p_transaction_id),'') is null then raise exception 'transaction_id_required'; end if;
  if coalesce(p_token_ciphertext,'') = '' or coalesce(p_token_iv,'') = '' or coalesce(p_token_tag,'') = '' then
    raise exception 'bad_token_envelope';
  end if;

  select * into v_row from public.membership_subscription_pilots
  where id = p_subscription_id and provider_ref = p_provider_ref
  for update;
  if not found then raise exception 'not_found'; end if;
  if v_row.status = 'active' and v_row.initial_transaction_id = p_transaction_id then
    return jsonb_build_object('status','active','already',true,'provider_ref',v_row.provider_ref);
  end if;
  if v_row.status <> 'pending' then raise exception 'invalid_status'; end if;

  update private.cardcom_subscription_credentials
  set token_ciphertext = p_token_ciphertext,
      token_iv = p_token_iv,
      token_tag = p_token_tag,
      expiration_mmyy = p_expiration_mmyy,
      updated_at = now()
  where subscription_id = p_subscription_id;

  update public.membership_subscription_pilots
  set status = 'active',
      initial_transaction_id = p_transaction_id,
      initial_document_url = nullif(btrim(coalesce(p_document_url,'')), ''),
      current_period_start = now(),
      current_period_end = now() + interval '1 month',
      next_charge_at = now() + interval '1 month',
      last_response_code = 0,
      updated_at = now()
  where id = p_subscription_id;

  update public.membership_subscription_pilot_charges
  set status = 'approved', cardcom_transaction_id = p_transaction_id,
      response_code = 0, document_url = nullif(btrim(coalesce(p_document_url,'')), ''),
      settled_at = now()
  where subscription_id = p_subscription_id and kind = 'initial';

  return jsonb_build_object('status','active','already',false,'provider_ref',p_provider_ref);
end
$$;

create or replace function public.membership_pilot_status(p_provider_ref text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public'
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.membership_subscription_pilots%rowtype;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  select * into v_row
  from public.membership_subscription_pilots
  where user_id = v_uid
    and (p_provider_ref is null or provider_ref = p_provider_ref)
  order by created_at desc limit 1;
  if not found then return jsonb_build_object('status','none'); end if;
  return jsonb_build_object(
    'provider_ref', v_row.provider_ref,
    'status', v_row.status,
    -- Owner-scoped opaque checkout ID permits GetLpResult reconciliation after
    -- returning to a protected Preview, whose external webhook may be blocked.
    'low_profile_id', case when v_row.status = 'pending' then v_row.cardcom_low_profile_id else null end,
    'amount_ils', v_row.amount_ils,
    'current_period_end', v_row.current_period_end,
    'next_charge_at', v_row.next_charge_at,
    'cancel_at_period_end', v_row.cancel_at_period_end,
    'document_url', v_row.initial_document_url
  );
end
$$;

create or replace function public.membership_pilot_claim_due(
  p_bridge_secret text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','private','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_row public.membership_subscription_pilots%rowtype;
  v_creds private.cardcom_subscription_credentials%rowtype;
  v_external text;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;

  update public.membership_subscription_pilots
  set status = 'cancelled', next_charge_at = null, updated_at = now()
  where status in ('active','past_due') and cancel_at_period_end and next_charge_at <= now();

  select * into v_row
  from public.membership_subscription_pilots
  where (
      (status = 'active' and not cancel_at_period_end and next_charge_at <= now())
      or (status = 'renewing' and updated_at < now() - interval '30 minutes')
    )
  order by next_charge_at, created_at
  for update skip locked
  limit 1;
  if not found then return jsonb_build_object('found', false); end if;

  v_external := 'M' || substr(replace(v_row.id::text,'-',''),1,12)
    || to_char(v_row.next_charge_at at time zone 'UTC','YYMMDDHH24MI');

  insert into public.membership_subscription_pilot_charges(
    subscription_id, external_uniq_tran_id, kind, amount_ils, status
  ) values (v_row.id, v_external, 'renewal', 2.00, 'pending')
  on conflict (external_uniq_tran_id) do nothing;

  update public.membership_subscription_pilots
  set status = 'renewing', updated_at = now()
  where id = v_row.id;

  select * into v_creds from private.cardcom_subscription_credentials
  where subscription_id = v_row.id;
  if v_creds.token_ciphertext is null then raise exception 'missing_token'; end if;

  return jsonb_build_object(
    'found', true,
    'subscription_id', v_row.id,
    'external_uniq_tran_id', v_external,
    'amount_ils', v_row.amount_ils,
    'token_ciphertext', v_creds.token_ciphertext,
    'token_iv', v_creds.token_iv,
    'token_tag', v_creds.token_tag,
    'expiration_mmyy', v_creds.expiration_mmyy,
    'billing_name', v_creds.billing_name,
    'billing_email', v_creds.billing_email
  );
end
$$;

create or replace function public.membership_pilot_settle_renewal(
  p_bridge_secret text,
  p_subscription_id uuid,
  p_external_uniq_tran_id text,
  p_success boolean,
  p_response_code integer,
  p_transaction_id text default null,
  p_document_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_hash constant text := 'b9b2b927e7c1337b8cc9ef33693eb1d9f58da14cd9ac21bc8ab8ad70dc1264ea';
  v_row public.membership_subscription_pilots%rowtype;
  v_charge public.membership_subscription_pilot_charges%rowtype;
begin
  if encode(extensions.digest(convert_to(coalesce(p_bridge_secret,''), 'UTF8'), 'sha256'), 'hex') <> v_hash then
    raise exception 'forbidden';
  end if;
  select * into v_row from public.membership_subscription_pilots
  where id = p_subscription_id for update;
  if not found then raise exception 'not_found'; end if;

  select * into v_charge
  from public.membership_subscription_pilot_charges
  where subscription_id = p_subscription_id
    and external_uniq_tran_id = p_external_uniq_tran_id
  for update;
  if not found then raise exception 'charge_not_found'; end if;
  if v_charge.status <> 'pending' then
    return jsonb_build_object(
      'status', v_row.status,
      'already', true,
      'charge_status', v_charge.status
    );
  end if;
  if v_row.status <> 'renewing' then raise exception 'invalid_status'; end if;
  if p_success and (p_response_code is distinct from 0 or nullif(btrim(p_transaction_id),'') is null) then
    raise exception 'verified_transaction_required';
  end if;

  update public.membership_subscription_pilot_charges
  set status = case when p_success then 'approved' else 'failed' end,
      response_code = p_response_code,
      cardcom_transaction_id = nullif(btrim(coalesce(p_transaction_id,'')), ''),
      document_url = nullif(btrim(coalesce(p_document_url,'')), ''),
      settled_at = now()
  where subscription_id = p_subscription_id
    and external_uniq_tran_id = p_external_uniq_tran_id;

  if p_success then
    update public.membership_subscription_pilots
    set status = 'active',
        current_period_start = current_period_end,
        current_period_end = current_period_end + interval '1 month',
        next_charge_at = current_period_end + interval '1 month',
        last_response_code = 0,
        failure_count = 0,
        updated_at = now()
    where id = p_subscription_id;
  else
    update public.membership_subscription_pilots
    set status = 'past_due',
        next_charge_at = null,
        last_response_code = p_response_code,
        failure_count = failure_count + 1,
        updated_at = now()
    where id = p_subscription_id;
  end if;
  return jsonb_build_object(
    'status', case when p_success then 'active' else 'past_due' end,
    'already', false
  );
end
$$;

create or replace function public.membership_pilot_cancel()
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.membership_subscription_pilots%rowtype;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  select * into v_row from public.membership_subscription_pilots
  where user_id = v_uid and status in ('active','past_due')
  order by created_at desc limit 1 for update;
  if not found then raise exception 'no_active_subscription'; end if;
  update public.membership_subscription_pilots
  set status = case when v_row.status = 'past_due' then 'cancelled' else status end,
      cancel_at_period_end = true,
      next_charge_at = case when v_row.status = 'past_due' then null else next_charge_at end,
      updated_at = now()
  where id = v_row.id;
  return jsonb_build_object(
    'status', case when v_row.status = 'past_due' then 'cancelled' else v_row.status end,
    'cancel_at_period_end', true,
    'current_period_end', v_row.current_period_end
  );
end
$$;

