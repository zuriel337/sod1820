-- READ-ONLY extraction of object DEFINITIONS (never rows) for the isolated QA stack. Run with the Supabase MCP execute_sql (or psql) as a read.
-- Parameters: edit the two arrays below. Output: one row per object (kind, name, ddl). Nothing here selects from a user table; it reads the
-- system catalogs only (pg_class, pg_attribute, pg_constraint, pg_index, pg_policies, pg_trigger, pg_proc, privileges).
-- The same output feeds scripts/build-qa-prod-definitions.mjs (generates the QA SQL) and scripts/qa-prod-parity.mjs (detects drift).
with params as (
  select array['users','direct_messages','user_notifications','notification_prefs','push_subscriptions','page_views','user_activity']::text[] as tables,
         array['dm_send','dm_inbox','dm_thread','notify_on_dm','push_subscription_upsert_v1','push_subscription_delete_v1','view_count']::text[] as fns
), tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace, params
  where n.nspname='public' and c.relkind='r' and c.relname = any(params.tables)
), cols as (
  select t.relname, string_agg('  '||quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)||case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end||case when a.attnotnull then ' not null' else '' end
         ||coalesce(' default '||pg_get_expr(d.adbin,d.adrelid),''), E',\n' order by a.attnum) body
  from tbl t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum group by t.relname
), inline_cons as (
  select t.relname, string_agg(E',\n  constraint '||quote_ident(co.conname)||' '||pg_get_constraintdef(co.oid), '' order by co.conname) body
  from tbl t join pg_constraint co on co.conrelid=t.oid and co.contype in ('p','u','c') group by t.relname
), fkeys as (
  select t.relname, co.conname, pg_get_constraintdef(co.oid) def, co.confrelid::regclass::text ref
  from tbl t join pg_constraint co on co.conrelid=t.oid and co.contype='f'
), rows as (
  select 'table' kind, 'public.'||t.relname nm, 'create table public.'||quote_ident(t.relname)||E' (\n'||c.body||coalesce(i.body,'')||E'\n);' ddl
  from tbl t join cols c using (relname) left join inline_cons i using (relname)
  union all
  select 'fk', 'public.'||relname||'.'||conname, 'alter table public.'||quote_ident(relname)||' add constraint '||quote_ident(conname)||' '||def||';' from fkeys
  union all
  select 'index', 'public.'||t.relname||'.'||ic.relname, pg_get_indexdef(i.indexrelid)||';'
  from tbl t join pg_index i on i.indrelid=t.oid and not i.indisprimary join pg_class ic on ic.oid=i.indexrelid
  where not exists (select 1 from pg_constraint co where co.conindid=i.indexrelid)
  union all
  select 'rls', 'public.'||relname, 'alter table public.'||quote_ident(relname)||' enable row level security;'||case when relforcerowsecurity then ' alter table public.'||quote_ident(relname)||' force row level security;' else '' end from tbl where relrowsecurity
  union all
  select 'policy', 'public.'||p.tablename||'.'||p.policyname,
         'create policy '||quote_ident(p.policyname)||' on public.'||quote_ident(p.tablename)||' as '||p.permissive||' for '||p.cmd||' to '||array_to_string(p.roles,', ')
         ||coalesce(' using ('||p.qual||')','')||coalesce(' with check ('||p.with_check||')','')||';'
  from pg_policies p, params where p.schemaname='public' and p.tablename = any(params.tables)
  union all
  select 'trigger', 'public.'||t.relname||'.'||tg.tgname, pg_get_triggerdef(tg.oid)||';'
  from tbl t join pg_trigger tg on tg.tgrelid=t.oid and not tg.tgisinternal
  union all
  select 'tablegrant', 'public.'||t.relname, string_agg('grant '||g.privilege_type||' on public.'||quote_ident(t.relname)||' to '||g.grantee||';', E'\n' order by g.grantee, g.privilege_type)
  from tbl t join information_schema.role_table_grants g on g.table_schema='public' and g.table_name=t.relname and g.grantee in ('anon','authenticated','service_role') group by t.relname
  union all
  select 'function', 'public.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')', pg_get_functiondef(p.oid)||';'
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace, params where n.nspname='public' and p.prokind='f' and p.proname = any(params.fns)
  union all
  select 'fngrant', 'public.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')',
         'revoke all on function public.'||quote_ident(p.proname)||'('||pg_get_function_identity_arguments(p.oid)||') from public;'
         ||coalesce((select string_agg(E'\ngrant execute on function public.'||quote_ident(p.proname)||'('||pg_get_function_identity_arguments(p.oid)||') to '||r.rolname||';', '' order by r.rolname)
                     from aclexplode(p.proacl) a join pg_roles r on r.oid=a.grantee where a.privilege_type='EXECUTE' and r.rolname in ('anon','authenticated','service_role')),'')
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace, params where n.nspname='public' and p.prokind='f' and p.proname = any(params.fns)
  union all
  select 'colgrant', 'public.'||q.relname, string_agg(q.stmt, E'\n' order by q.stmt) from (
    select t2.relname, 'grant '||lower(x.privilege_type)||' ('||string_agg(quote_ident(a.attname), ', ' order by a.attnum)||') on public.'||quote_ident(t2.relname)||' to '||r.rolname||';' stmt
    from tbl t2 join pg_attribute a on a.attrelid=t2.oid and a.attnum>0 and not a.attisdropped and a.attacl is not null
    cross join lateral aclexplode(a.attacl) x join pg_roles r on r.oid=x.grantee and r.rolname in ('anon','authenticated','service_role')
    group by t2.relname, x.privilege_type, r.rolname) q group by q.relname
  union all
  -- dependencies a reviewer must look at: other public functions and tables the scoped functions call, not in scope
  select 'dependency', 'public.'||p.proname||' -> '||o.proname, 'review'
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace join params on true
  join pg_proc o on o.pronamespace=n.oid and o.prokind='f' and o.proname<>p.proname and p.prosrc ~* ('(^|[^a-z_0-9.])(public\.)?'||o.proname||'\s*\(')
  where n.nspname='public' and p.proname = any(params.fns) and not (o.proname = any(params.fns))
)
select kind, nm as name, md5(ddl) as md5, ddl from rows order by array_position(array['table','fk','index','rls','policy','function','trigger','tablegrant','colgrant','fngrant','dependency'], kind), nm;
