create schema if not exists auth;
create or replace function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
create or replace function auth.role() returns text language sql stable as $$ select nullif(current_setting('test.role', true), '') $$;

create schema if not exists net;
create table net.calls (id bigserial primary key, url text, body jsonb, params jsonb, headers jsonb, timeout_milliseconds integer, at timestamptz default clock_timestamp());
create table net._http_response (id bigint, status_code integer, content_type text, headers jsonb, content text, timed_out boolean, error_msg text,
  created timestamptz not null default now());
create function net.http_post(url text, body jsonb default '{}'::jsonb, params jsonb default '{}'::jsonb,
  headers jsonb default '{"Content-Type": "application/json"}'::jsonb, timeout_milliseconds integer default 5000)
returns bigint language plpgsql as $$
declare v bigint;
begin
  if current_setting('test.net_down', true) = 'on' then raise exception 'pg_net queue unavailable (test)'; end if;
  insert into net.calls (url, body, params, headers, timeout_milliseconds) values (url, body, params, headers, timeout_milliseconds) returning id into v;
  return v;
end $$;

