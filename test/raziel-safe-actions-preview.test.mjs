import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { buildRazielSafeActionsPreviewFixture, buildRazielSafeActionsPreviewWorker } from "./helpers/raziel-safe-actions-preview-fixture.mjs";
import { normalizeRazielResponse } from "../src/lib/research/razielSessionRequest2029.js";

const builder = readFileSync(new URL("../scripts/build-integrated-preview.mjs", import.meta.url), "utf8");
const start = builder.indexOf("const allow =");
const end = builder.indexOf('await writeFile(resolve(output, "preview-readonly-sw.js")');
const base = vm.runInNewContext(builder.slice(start, end) + "\nworker;");
const selectorStart = builder.indexOf("const legacyMockBranch =");
const selectorEnd = builder.indexOf("const selectedMockBranch =");
const selectMockPreviewBranch = vm.runInNewContext(
  builder.slice(selectorStart, selectorEnd) + "\nselectMockPreviewBranch;",
);

async function request(path, { body = {}, origin = "https://linswmnnkjxvweumprav.supabase.co" } = {}) {
  let handler, output, forwarded = 0;
  const worker = buildRazielSafeActionsPreviewWorker(base);
  vm.runInNewContext(worker, {
    self: { addEventListener: (name, fn) => { if (name === "fetch") handler = fn; } },
    URL, Request, Response,
    fetch: async () => { forwarded++; return Response.json({ error: "unexpected_live_io" }); },
  });
  handler({ request: new Request(origin + path, { method: "POST", body: JSON.stringify(body) }), respondWith: value => { output = value; } });
  const response = output ? await output : null;
  return { response, forwarded };
}

test("Preview suggestions are generated by the real server registry and labelled as mock-only", () => {
  const fixture = buildRazielSafeActionsPreviewFixture();
  assert.deepEqual(JSON.parse(JSON.stringify(fixture.expression.raziel.suggested_paths.map(a => a.id))), ["all_methods", "open_number"]);
  assert.deepEqual(JSON.parse(JSON.stringify(fixture.save.raziel.suggested_paths.map(a => a.id))), ["save_conversation"]);
  assert.deepEqual(JSON.parse(JSON.stringify(fixture.methods.raziel.suggested_paths.map(a => a.id))), ["open_number", "save_conversation"]);
  for (const value of [fixture.expression, fixture.methods, fixture.save]) {
    assert.match(value.raziel.answer, /תשובת דמה/);
    assert.equal(value.model, "preview:mock-only");
    assert.ok(value.raziel.suggested_paths.length <= 2);
    assert.ok(normalizeRazielResponse(value.raziel)?.answer);
  }
});

test("mocked transport never calls a model or backend, including malicious suggested_paths", async () => {
  const { response, forwarded } = await request("/functions/v1/ai-analyze", { body: {
    persona: "raziel", subject: "מה זה משיח?", suggested_paths: [{ id: "delete_everything", href: "https://evil.test" }],
  } });
  assert.equal(response.status, 200);
  assert.equal(forwarded, 0);
  assert.equal(response.headers.get("X-Raziel-Preview-Transport"), "mock-only");
  const data = await response.json();
  assert.doesNotMatch(JSON.stringify(data), /evil|delete_everything/);
  assert.equal(data.raziel.suggested_paths[1].href, "/2029/number/358");
  assert.equal(normalizeRazielResponse(data.raziel).suggestedActions.length, 2);
});

test("explicit all-method continuation and save suggestion still use the existing contract", async () => {
  for (const [subject, expected] of [["בדוק את משיח בכל השיטות", "open_number"], ["שמור שיחה", "save_conversation"]]) {
    const { response, forwarded } = await request("/functions/v1/ai-analyze", { body: { persona: "raziel", subject } });
    assert.equal(forwarded, 0);
    assert.equal((await response.json()).raziel.suggested_paths[0].id, expected);
  }
});

test("guest denial fixture is explicit, server-shaped and never counts requests or invents limits", async () => {
  for (let attempt = 0; attempt < 2; attempt++) {
    const { response, forwarded } = await request("/functions/v1/ai-analyze", { body: {
      persona: "raziel", subject: "בדיקת מכסת אורח",
    } });
    assert.equal(forwarded, 0);
    assert.equal(response.headers.get("X-Raziel-Preview-Transport"), "mock-only");
    assert.deepEqual(await response.json(), {
      error: "quota", tier: "anon", surface: "raziel", model: "preview:mock-only",
    });
  }
  // A different explicit question still works; the fixture has no quota state.
  const { response } = await request("/functions/v1/ai-analyze", { body: {
    persona: "raziel", subject: "מה זה משיח?",
  } });
  assert.ok((await response.json()).raziel.answer);
});

test("mock configuration cannot admit real product writes, new Person creation or a different AI persona", async () => {
  for (const [path, body] of [
    ["/functions/v1/ai-analyze", { persona: "other" }],
    ["/rest/v1/rpc/research_state_apply_v1", {}],
    ["/rest/v1/rpc/fn_get_or_create_my_person", {}],
    ["/rest/v1/rpc/fn_upsert_self_profile", {}],
    ["/rest/v1/rpc/fn_upsert_family_member", {}],
    ["/functions/v1/els-search-bridge", { op: "save" }],
    ["/storage/v1/object/public/example", {}],
  ]) {
    const { response, forwarded } = await request(path, { body });
    assert.equal(response.status, 403, path);
    assert.equal(forwarded, 0, path);
  }
  const { response } = await request("/functions/v1/ai-analyze", { origin: "https://evil.test", body: { persona: "raziel" } });
  assert.equal(response.status, 403);
});

test("mock Preview selection admits only the exact reviewed branches", () => {
  for (const branch of [
    "gpt/2029-central-raziel-safe-actions-integration-20261026",
    "gpt/2029-central-raziel-personal-navigation-integration-20261026",
    "gpt/2029-central-unified-workspace-20261029",
    "gpt/2029-central-shell-alignment-20261029",
    "gpt/2029-central-topbar-menu-completion-20261029",
    "gpt/2029-central-ui-carry-restoration-20261029",
    "gpt/2029-central-community-filter-tiles-20261029",
  ]) {
    assert.equal(selectMockPreviewBranch({
      VERCEL_ENV: "preview",
      VERCEL_GIT_COMMIT_REF: branch,
    }), branch);
  }

  assert.equal(selectMockPreviewBranch({
    VERCEL_ENV: "preview",
    VERCEL_GIT_COMMIT_REF: "gpt/unreviewed-preview-branch",
  }), null);
  assert.throws(() => selectMockPreviewBranch({
    SOD_RAZIEL_SAFE_ACTIONS_PREVIEW: "true",
    VERCEL_ENV: "preview",
    VERCEL_GIT_COMMIT_REF: "gpt/unreviewed-preview-branch",
  }), /mock_preview_branch_mismatch/);
  assert.throws(() => selectMockPreviewBranch({
    SOD_RAZIEL_SAFE_ACTIONS_PREVIEW: "true",
    VERCEL_ENV: "production",
    VERCEL_GIT_COMMIT_REF: "gpt/2029-central-raziel-personal-navigation-integration-20261026",
  }), /mock_preview_is_never_production/);
});
